def get_base_length(mass, temp, alt, table_dict, temp_vals):
    if alt <= alt_vals_takeoff[0]:
        alt_low = alt_high = alt_vals_takeoff[0]
    elif alt >= alt_vals_takeoff[-1]:
        alt_low = alt_high = alt_vals_takeoff[-1]
    else:
        for i in range(len(alt_vals_takeoff)-1):
            if alt_vals_takeoff[i] <= alt <= alt_vals_takeoff[i+1]:
                alt_low, alt_high = alt_vals_takeoff[i], alt_vals_takeoff[i+1]
                break

    grid_low = table_dict[alt_low]
    grid_high = table_dict[alt_high]

    val_low = bilinear_interpolate(mass, temp, mass_vals, temp_vals, grid_low)
    val_high = bilinear_interpolate(mass, temp, mass_vals, temp_vals, grid_high)

    if alt_low == alt_high:
        return val_low
    else:
        return linear_interpolate(alt, alt_low, alt_high, val_low, val_high)

def get_factor_from_table(mass, x, x_vals, table, table_mass_vals):
    if x <= x_vals[0]:
        xi1 = xi2 = 0
    elif x >= x_vals[-1]:
        xi1 = xi2 = len(x_vals)-1
    else:
        for i in range(len(x_vals)-1):
            if x_vals[i] <= x <= x_vals[i+1]:
                xi1, xi2 = i, i+1
                break
    if mass <= table_mass_vals[0]:
        mi1 = mi2 = 0
    elif mass >= table_mass_vals[-1]:
        mi1 = mi2 = len(table_mass_vals)-1
    else:
        for i in range(len(table_mass_vals)-1):
            if table_mass_vals[i] <= mass <= table_mass_vals[i+1]:
                mi1, mi2 = i, i+1
                break

    if xi1 == xi2 and mi1 == mi2:
        val_x = table[xi1][mi1]
    else:
        if mi1 != mi2:
            y_low = linear_interpolate(mass, table_mass_vals[mi1], table_mass_vals[mi2],
                                        table[xi1][mi1], table[xi1][mi2])
            y_high = linear_interpolate(mass, table_mass_vals[mi1], table_mass_vals[mi2],
                                         table[xi2][mi1], table[xi2][mi2])
        else:
            y_low = table[xi1][mi1]
            y_high = table[xi2][mi1]
        if xi1 != xi2:
            val_x = linear_interpolate(x, x_vals[xi1], x_vals[xi2], y_low, y_high)
        else:
            val_x = y_low

    zero_idx = None
    if 0 in x_vals:
        zero_idx = x_vals.index(0)
    elif 0.0 in x_vals:
        zero_idx = x_vals.index(0.0)
    if zero_idx is not None:
        if mi1 != mi2:
            val_zero = linear_interpolate(mass, table_mass_vals[mi1], table_mass_vals[mi2],
                                          table[zero_idx][mi1], table[zero_idx][mi2])
        else:
            val_zero = table[zero_idx][mi1]
        if val_zero == 0:
            return 1.0
        return val_x / val_zero
    else:
        return 1.0

